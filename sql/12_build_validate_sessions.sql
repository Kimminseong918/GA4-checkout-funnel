/*
[목적]
- 세션 테이블(p1.sessions)이 제대로 만들어졌는지 검증 (03번 일별 집계와 대조)

[결과 요약]
- 세션 전환율: 시즌 전 1.28% / 시즌 1.91% / 연휴 0.84% / 비시즌 0.99%
- 세션 수: 시즌 124,133 / 비시즌 107,189, 구매 세션: 시즌 2,369 / 비시즌 1,059
- 시즌 구매 세션 2,369건이 03번 일별 집계와 정확히 일치

[판단]
- 세션 테이블 검증 완료 → 이후 분석의 기준 테이블로 사용
- 시즌 성과 확인: 전환율이 비시즌의 약 1.9배 (하루 세션 +20%, 하루 구매 세션 2.3배)

[참고사항]
- 비시즌 구매 세션 차이(일별 1,072 vs 세션 테이블 1,059, −13건)
  → 03번은 이벤트 날짜, 세션 테이블은 방문 시작일 기준이라 생긴 차이
- 연휴 전환율(0.84%)이 비시즌보다도 낮음 → 연휴를 비교에서 제외한 근거
*/

SELECT
  period,
  COUNT(*)      AS sessions,
  SUM(purchase) AS purchase_sessions
FROM `modulabs-project-465602.p1.sessions`
GROUP BY period
ORDER BY period;
